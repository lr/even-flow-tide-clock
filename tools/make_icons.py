#!/usr/bin/env python3
"""
Convert the Meteocons SVGs in assets/meteocons into LVGL image data.

    python3 tools/make_icons.py

Writes src/ui/icons/meteocons.c and .h. Run it again only when icons or sizes
change; the output is committed so normal builds need neither tool.

Needs `rsvg-convert` (brew install librsvg) and Pillow.

Images are RGB565A8 (16-bit colour plus an 8-bit alpha plane), the panel's
native format, so the board draws them straight from flash with no decoding.
All icons share one crop so they keep the same scale relative to each other.
"""
import os
import subprocess
import sys
import tempfile

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "meteocons")
OUT = os.path.join(ROOT, "src", "ui", "icons")
SIZES = (64, 40)  # center icon, ring icons
RENDER = 512      # the SVGs' native artboard


def c_name(name, size):
    return "mc_" + name.replace("-", "_") + f"_{size}"


def rgb565a8(img):
    """Colour plane (little-endian RGB565) followed by the alpha plane."""
    w, h = img.size
    color = bytearray()
    alpha = bytearray()
    for r, g, b, a in img.getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        color += bytes((v & 0xFF, v >> 8))
        alpha.append(a)
    return bytes(color + alpha), w * 2


def main():
    names = sorted(f[:-4] for f in os.listdir(SRC) if f.endswith(".svg"))
    if not names:
        sys.exit("no SVGs in " + SRC)

    with tempfile.TemporaryDirectory() as tmp:
        big = {}
        for n in names:
            png = os.path.join(tmp, n + ".png")
            subprocess.run(["rsvg-convert", "-w", str(RENDER), "-h", str(RENDER), "-o", png,
                            os.path.join(SRC, n + ".svg")], check=True)
            big[n] = Image.open(png).convert("RGBA")

    # Smallest square that contains every icon's visible pixels
    boxes = [im.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox() for im in big.values()]
    left = min(b[0] for b in boxes)
    top = min(b[1] for b in boxes)
    right = max(b[2] for b in boxes)
    bottom = max(b[3] for b in boxes)
    side = max(right - left, bottom - top)
    cx, cy = (left + right) // 2, (top + bottom) // 2
    crop = (cx - side // 2, cy - side // 2, cx - side // 2 + side, cy - side // 2 + side)

    os.makedirs(OUT, exist_ok=True)
    total = 0
    with open(os.path.join(OUT, "meteocons.c"), "w") as c:
        c.write("/* Generated by tools/make_icons.py from assets/meteocons. Do not edit.\n"
                " * Meteocons by Bas Milius, MIT licence (assets/meteocons/LICENSE). */\n"
                '#include "meteocons.h"\n\n')
        for n in names:
            for size in SIZES:
                img = big[n].crop(crop).resize((size, size), Image.LANCZOS)
                data, stride = rgb565a8(img)
                total += len(data)
                sym = c_name(n, size)
                c.write(f"static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {sym}_map[] = {{\n")
                for i in range(0, len(data), 24):
                    c.write("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
                c.write("};\n\n")
                c.write(f"const lv_image_dsc_t {sym} = {{\n"
                        f"    .header = {{\n"
                        f"        .magic = LV_IMAGE_HEADER_MAGIC,\n"
                        f"        .cf = LV_COLOR_FORMAT_RGB565A8,\n"
                        f"        .w = {size},\n"
                        f"        .h = {size},\n"
                        f"        .stride = {stride},\n"
                        f"    }},\n"
                        f"    .data_size = sizeof({sym}_map),\n"
                        f"    .data = {sym}_map,\n"
                        f"}};\n\n")

    with open(os.path.join(OUT, "meteocons.h"), "w") as h:
        h.write("/* Generated by tools/make_icons.py. Do not edit. */\n"
                "#ifndef METEOCONS_H\n#define METEOCONS_H\n\n#include \"lvgl.h\"\n\n")
        for n in names:
            for size in SIZES:
                h.write(f"extern const lv_image_dsc_t {c_name(n, size)};\n")
        h.write("\n#endif /* METEOCONS_H */\n")

    print(f"{len(names)} icons x {len(SIZES)} sizes, {total / 1024:.0f} KB of image data, crop {crop}")


if __name__ == "__main__":
    main()
